//! The C+F mapping differs from pinned unicode-casefold 0.2.0 / Unicode 9
//! at exactly 156 scalars, all single-scalar additions. Complete comparison
//! found no removed mapping requiring an identity override. The override
//! lookup can represent identity rows as well; unlisted scalars retain the
//! legacy full mapping, including expansions and Cherokee uppercase folds.
//! No compiler lowercase tables, Unicode normalization, or whitespace rules.
use unicode_casefold::UnicodeCaseFold;

// The delta is relative to this exact baseline, not to the compiler's UCD.
const _: () = {
    let version = unicode_casefold::UNICODE_VERSION;
    assert!(version.0 == 9 && version.1 == 0 && version.2 == 0);
};

pub(crate) fn fold(value: &str) -> String {
    let mut output = String::with_capacity(value.len());
    for character in value.chars() {
        match DELTA_9_TO_16.binary_search_by_key(&character, |row| row.0) {
            Ok(index) => output.push(DELTA_9_TO_16[index].1),
            Err(_) => output.extend(std::iter::once(character).case_fold()),
        }
    }
    output
}

